"""Tally SL central licensing (GSTR2Tally and future Tally-based apps).

Isolated by design: every table here is NEW (prefix `tallysl_`). Nothing in apps.registrations (Barcode Auto Print) is
altered, imported for writing, or joined. Tally Serial Number == Product Serial Number == User ID (`tally_serial`).
"""
import uuid

from django.conf import settings
from django.db import models
from django.db.models import Q


class TallyProduct(models.Model):
    """The product registry. A new Tally SL application is a row here (plus an API key) - no code change."""

    code = models.SlugField(max_length=40, unique=True)
    name = models.CharField(max_length=80)
    kind = models.CharField(max_length=20, default="tally-addon")  # gstr | dotnet | python | tally-addon (informational)
    active = models.BooleanField(default=True)
    default_trial_days = models.PositiveSmallIntegerField(default=3)
    password_reset_url = models.CharField(max_length=300, blank=True, default="")  # e.g. gstr2tally://reset-password
    activation_link_base = models.CharField(max_length=300, blank=True, default="")  # e.g. gstr2tally://activate
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["name"]

    def __str__(self):
        return self.code


class TallyProductKey(models.Model):
    """Credential a product's local client/agent uses to identify itself (X-Product-Key). Only the hash is stored."""

    product = models.ForeignKey(TallyProduct, on_delete=models.CASCADE, related_name="keys")
    label = models.CharField(max_length=80, blank=True, default="")
    key_hash = models.CharField(max_length=64, unique=True)
    active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)


class TallyCustomer(models.Model):
    ACTIVE, LOCKED = "ACTIVE", "LOCKED"

    product = models.ForeignKey(TallyProduct, on_delete=models.PROTECT, related_name="customers")
    tally_serial = models.CharField(max_length=30)  # = Product Serial Number = User ID (never generated by Nexus)
    name = models.CharField(max_length=100)
    email = models.EmailField()
    contact_number = models.CharField(max_length=20)
    password_hash = models.CharField(max_length=256)
    must_change_password = models.BooleanField(default=True)
    password_changed_at = models.DateTimeField(null=True, blank=True)
    failed_logins = models.PositiveSmallIntegerField(default=0)
    locked_until = models.DateTimeField(null=True, blank=True)
    welcome_email_status = models.CharField(max_length=20, blank=True, default="")
    registered_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-id"]
        constraints = [models.UniqueConstraint(fields=["product", "tally_serial"], name="uniq_tally_customer_serial_per_product")]

    @property
    def user_id(self):
        return self.tally_serial


class TallyInfo(models.Model):
    """Tally license details reported by the local GSTR client. Only verified values are kept; `availability` records,
    per field, whether the client verified it ('verified') or could not read it ('unavailable')."""

    customer = models.OneToOneField(TallyCustomer, on_delete=models.CASCADE, related_name="tally_info")
    edition = models.CharField(max_length=60, blank=True, default="")
    tss_details = models.CharField(max_length=300, blank=True, default="")
    virtual_user_limit = models.PositiveIntegerField(null=True, blank=True)
    license_administrator = models.CharField(max_length=150, blank=True, default="")
    gateway_server = models.CharField(max_length=200, blank=True, default="")
    registered_email = models.CharField(max_length=254, blank=True, default="")
    tss_expiry_date = models.DateField(null=True, blank=True)  # Tally/TSS expiry - NOT the Nexus licence expiry
    availability = models.TextField(blank=True, default="{}")  # JSON {field: verified|unavailable}
    reported_at = models.DateTimeField(null=True, blank=True)
    reported_device = models.ForeignKey("TallyDevice", null=True, blank=True, on_delete=models.SET_NULL, related_name="+")


class TallyLicense(models.Model):
    """One Nexus software licence per customer. Registration creates it PENDING (no access); a Superadmin activates it."""

    TRIAL, LICENSED, LIFETIME = "TRIAL", "LICENSED", "LIFETIME"
    TYPES = [(TRIAL, "Trial"), (LICENSED, "Licensed (1 Year)"), (LIFETIME, "Lifetime")]
    PENDING, ACTIVE, TRIAL_CANCELLED, INACTIVE = "PENDING", "ACTIVE", "TRIAL_CANCELLED", "INACTIVE"

    customer = models.OneToOneField(TallyCustomer, on_delete=models.CASCADE, related_name="license")
    license_type = models.CharField(max_length=10, choices=TYPES, default=TRIAL)
    status = models.CharField(max_length=20, default=PENDING)
    trial_days = models.PositiveSmallIntegerField(null=True, blank=True)
    activated_at = models.DateTimeField(null=True, blank=True)
    expires_at = models.DateTimeField(null=True, blank=True)  # Nexus software licence expiry (null = Lifetime / not started)
    activation_key_hash = models.CharField(max_length=64, blank=True, default="", db_index=True)
    activation_key_suffix = models.CharField(max_length=4, blank=True, default="")
    activation_key_issued_at = models.DateTimeField(null=True, blank=True)
    activation_key_email_status = models.CharField(max_length=20, blank=True, default="")
    activated_by = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    updated_at = models.DateTimeField(auto_now=True)


class TallyDevice(models.Model):
    """A computer enrolled for a customer. One ACTIVE (not revoked) device per customer, enforced by the database.
    Only a keyed hash of the machine identity is stored."""

    device_id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    customer = models.ForeignKey(TallyCustomer, on_delete=models.CASCADE, related_name="devices")
    client_device_id = models.CharField(max_length=64)  # stable id the client generated for this installation
    fingerprint_hash = models.CharField(max_length=64)
    device_name = models.CharField(max_length=100, blank=True, default="")
    app_version = models.CharField(max_length=30, blank=True, default="")
    generation = models.PositiveIntegerField(default=1)
    enrolled_at = models.DateTimeField(auto_now_add=True)
    last_seen_at = models.DateTimeField(null=True, blank=True)
    revoked_at = models.DateTimeField(null=True, blank=True)
    revoked_reason = models.CharField(max_length=200, blank=True, default="")

    class Meta:
        ordering = ["-enrolled_at"]
        constraints = [
            models.UniqueConstraint(fields=["customer"], condition=Q(revoked_at__isnull=True), name="uniq_tally_active_device_per_customer"),
        ]


class TallyDeviceTransfer(models.Model):
    """History of every enrollment / replacement. Never deleted."""

    ENROLLED, REPLACED, REVOKED = "ENROLLED", "REPLACED", "REVOKED"

    customer = models.ForeignKey(TallyCustomer, on_delete=models.CASCADE, related_name="transfers")
    kind = models.CharField(max_length=10)
    from_device = models.ForeignKey(TallyDevice, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    to_device = models.ForeignKey(TallyDevice, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    performed_by = models.CharField(max_length=150, blank=True, default="")  # 'customer' or the staff username
    ip_address = models.CharField(max_length=45, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-id"]


class TallyVerificationCode(models.Model):
    """Short-lived, single-use emailed code for Activate User. Only hashes are stored. After the code (+ activation key)
    is verified a single-use `ticket` is issued for the final Confirm step."""

    customer = models.ForeignKey(TallyCustomer, on_delete=models.CASCADE, related_name="verification_codes")
    code_hash = models.CharField(max_length=64)
    attempts = models.PositiveSmallIntegerField(default=0)
    expires_at = models.DateTimeField()
    verified_at = models.DateTimeField(null=True, blank=True)
    ticket_hash = models.CharField(max_length=64, blank=True, default="", db_index=True)
    ticket_expires_at = models.DateTimeField(null=True, blank=True)
    consumed_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)


class TallySession(models.Model):
    """A signed-in client session. Server-side so it can be revoked at once (device replaced, password changed)."""

    customer = models.ForeignKey(TallyCustomer, on_delete=models.CASCADE, related_name="sessions")
    device = models.ForeignKey(TallyDevice, null=True, blank=True, on_delete=models.SET_NULL, related_name="sessions")
    client_device_id = models.CharField(max_length=64, blank=True, default="")
    token_hash = models.CharField(max_length=64, unique=True)
    expires_at = models.DateTimeField()
    revoked_at = models.DateTimeField(null=True, blank=True)
    revoked_reason = models.CharField(max_length=60, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)


class TallyPasswordReset(models.Model):
    """One-time reset token (hash only). Using it, or issuing a newer one, invalidates it."""

    customer = models.ForeignKey(TallyCustomer, on_delete=models.CASCADE, related_name="password_resets")
    token_hash = models.CharField(max_length=64, unique=True)
    expires_at = models.DateTimeField()
    used_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)


class TallyUsageEvent(models.Model):
    """A successful application open / login on an enrolled, authorised device."""

    customer = models.ForeignKey(TallyCustomer, on_delete=models.CASCADE, related_name="usage_events")
    device = models.ForeignKey(TallyDevice, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    kind = models.CharField(max_length=10, default="open")  # open | login
    app_version = models.CharField(max_length=30, blank=True, default="")
    occurred_at = models.DateTimeField(db_index=True)
    day = models.DateField(db_index=True)  # local (Asia/Kolkata) calendar day, for distinct-days counting

    class Meta:
        indexes = [models.Index(fields=["customer", "day"], name="tallysl_usage_cust_day")]


class TallyUsageRule(models.Model):
    """Configurable classification thresholds (one row, pk=1)."""

    new_user_days = models.PositiveSmallIntegerField(default=7)
    speed_window_days = models.PositiveSmallIntegerField(default=30)
    speed_min_active_days = models.PositiveSmallIntegerField(default=15)
    updated_at = models.DateTimeField(auto_now=True)


class TallyAuditLog(models.Model):
    """Append-only security / licence audit trail for Tally SL."""

    product = models.ForeignKey(TallyProduct, null=True, blank=True, on_delete=models.SET_NULL, related_name="+")
    customer = models.ForeignKey(TallyCustomer, null=True, blank=True, on_delete=models.SET_NULL, related_name="audit")
    action = models.CharField(max_length=40, db_index=True)
    detail = models.CharField(max_length=300, blank=True, default="")
    actor = models.CharField(max_length=150, blank=True, default="")  # staff username, 'customer' or 'system'
    ip_address = models.CharField(max_length=45, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-id"]


class TallyAdminPermission(models.Model):
    """Per-Admin, per-PRODUCT grants. Separate from the PRN permission tables, which are untouched."""

    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="tally_permissions")
    product = models.ForeignKey(TallyProduct, on_delete=models.CASCADE, related_name="admin_permissions")
    can_view = models.BooleanField(default=False)
    can_entry = models.BooleanField(default=False)
    can_edit = models.BooleanField(default=False)
    can_delete = models.BooleanField(default=False)
    can_license_activation = models.BooleanField(default=False)
    can_license_management = models.BooleanField(default=False)
    can_reports = models.BooleanField(default=False)
    can_device_management = models.BooleanField(default=False)

    class Meta:
        constraints = [models.UniqueConstraint(fields=["user", "product"], name="uniq_tally_admin_permission")]


